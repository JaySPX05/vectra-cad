"""Convert a Hershey .jhf font (one glyph per line, ASCII 32..126 in order) to a TypeScript module.

Usage: python -I scripts/jhf_to_ts.py <rowmans.jhf> <out.ts>

JHF format: cols 0-4 glyph id, 5-7 vertex count, then character pairs; each pair is (x, y) with
value = ord(c) - ord('R'); the first pair is the left/right bearing; " R" lifts the pen.
Hershey y grows downward; for Roman Simplex the baseline is y = 9 and cap height is 21 units.
"""
import json
import sys

src, dst = sys.argv[1], sys.argv[2]
lines = [l.rstrip("\n\r") for l in open(src, encoding="ascii") if l.strip()]
# glyph records may wrap onto continuation lines: join by declared vertex count
records = []
buf = ""
for l in lines:
    buf = l if not buf else buf + l
    count = int(buf[5:8])
    if len(buf) - 8 >= count * 2:
        records.append(buf)
        buf = ""
assert len(records) in (95, 96), len(records)

CAP, BASE = 21.0, 9
glyphs = []
for rec in records:
    count = int(rec[5:8])
    data = rec[8:8 + count * 2]
    left, right = ord(data[0]) - 82, ord(data[1]) - 82
    strokes, cur = [], []
    for i in range(2, len(data), 2):
        pair = data[i:i + 2]
        if pair == " R":
            if len(cur) >= 4:
                strokes.append(cur)
            cur = []
            continue
        x, y = ord(pair[0]) - 82, ord(pair[1]) - 82
        cur += [round((x - left) / CAP, 4), round((BASE - y) / CAP, 4)]
    if len(cur) >= 4:
        strokes.append(cur)
    glyphs.append({"a": round((right - left) / CAP, 4), "s": strokes})

header = """// Generated by scripts/jhf_to_ts.py from rowmans.jhf (Hershey Roman Simplex) - do not edit.
//
// Roman Simplex is the single-stroke design AutoCAD's romans.shx reproduces.
// Acknowledgements required by the Hershey font licence:
//   - The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the
//     U. S. National Bureau of Standards.
//   - The format of the Font data in this distribution was originally created by
//     James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821.
//
// Units: cap height = 1, origin at the left bearing on the baseline, y up.
// Each glyph: a = advance width, s = strokes (flat x,y lists, pen down along each).

export interface StrokeGlyph {
  a: number;
  s: number[][];
}

/** ASCII 32..126 (plus glyph 718 at index 95), indexed by charCode - 32. */
export const ROMANS_GLYPHS: StrokeGlyph[] = """
open(dst, "w", encoding="utf-8").write(header + json.dumps(glyphs, separators=(",", ":")) + ";\n")
print("wrote", dst, len(glyphs), "glyphs")
